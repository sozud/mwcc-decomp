#!/usr/bin/env python3
"""Write 3.0-011126's name map and glue from b69's, translating every b69 address (vamap.json).

    gen_from_b69.py

tools/mwccps2/b69/{symbols*.txt, functions.csv, units.txt, glue/*} -> tools/mwccps2/b011126/.
Addresses with no 011126 counterpart are dropped (listed in dropped.txt). Glue entries that name
b145 addresses are copied as they are; b69 addresses in their comments are translated.
"""

import csv
import os
import re
import shutil
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import vamap  # noqa: E402

B = vamap.B
SRC = os.path.join(os.path.dirname(B), "b69")


def main():
    tr = vamap.load()
    dropped = []
    os.makedirs(os.path.join(B, "glue"), exist_ok=True)

    sym_re = re.compile(r"^(\s*[\w./+$?@-]+\s*=\s*)0x([0-9A-Fa-f]+)(\s*;.*)$")
    for f in ("symbols.txt", "symbols.derived.txt", "symbols.manual.txt", "symbols.guess.txt", "symbols.guess145.txt"):
        out = [f"// Generated by tools/mwccps2/b011126/re/gen_from_b69.py from b69's {f} (b69 address in the comment)."]
        for line in open(os.path.join(SRC, f)):
            line = line.rstrip("\n")
            m = sym_re.match(line)
            if not m:
                out.append(line)
                continue
            va = int(m.group(2), 16)
            n = tr(va)
            if n is None:
                dropped.append(f"{f}: {line}")
                continue
            out.append(f"{m.group(1)}0x{n:08X}{m.group(3)} // b69 0x{va:08X}")
        open(os.path.join(B, f), "w").write("\n".join(out) + "\n")

    rows = list(csv.DictReader(open(os.path.join(SRC, "functions.csv"))))
    with open(os.path.join(B, "functions.csv"), "w") as fo:
        fo.write("start,size,unit\n")
        for r in rows:
            n = tr(int(r["start"], 16))
            if n is None:
                dropped.append(f"functions.csv: {r['start']} {r['unit']}")
                continue
            fo.write(f"{n:08x},{r['size']},{r['unit']}\n")

    for f in ("text_names.txt", "image_labels.txt"):
        out = []
        for line in open(os.path.join(SRC, "glue", f)):
            p = line.split(None, 1)
            if len(p) < 2:
                continue
            n = tr(int(p[0], 16))
            if n is None:
                dropped.append(f"glue/{f}: {line.strip()}")
                continue
            out.append(f"{n:08X} {p[1].rstrip()}")
        open(os.path.join(B, "glue", f), "w").write("\n".join(out) + "\n")

    def b69_comment(m):
        n = tr(int(m.group(1), 16))
        return f"(b69 {m.group(1)}: 011126 {n:08X}" if n is not None else f"(b69 {m.group(1)}: no 011126 address"

    for f in ("alias.txt", "bss.txt", "code.txt", "data.txt", "dead.txt"):
        text = open(os.path.join(SRC, "glue", f)).read()
        text = re.sub(r"\(b69 ([0-9A-F]{8})", b69_comment, text)
        open(os.path.join(B, "glue", f), "w").write(text)
    shutil.copyfile(os.path.join(SRC, "glue", "b145_map.json"), os.path.join(B, "glue", "b145_map.json"))
    shutil.copyfile(os.path.join(SRC, "units.txt"), os.path.join(B, "units.txt"))
    open(os.path.join(B, "dropped.txt"), "w").write("\n".join(dropped) + "\n")
    print(f"dropped {len(dropped)} entries with no 011126 address -> dropped.txt")


if __name__ == "__main__":
    main()
