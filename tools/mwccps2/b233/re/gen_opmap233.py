#!/usr/bin/env python3
"""2.3.3's opcode table against ours: src/psp/backend/OpMap233.c.

    python3 tools/mwccps2/b233/re/gen_opmap233.py

2.3.3 builds its table (0x549510, 0x2A-byte entries, macros from 0x3BD) in
0x48A600 by calls to 0x48A400 (op, name, format, encoding, flags, intrinsic,
unit, latency class), 0x48A510 (the same with the encoding as a bit string
and no intrinsic) and 0x48A550 (macros: op, name, format, real, alt,
latency class). Our table is OpcodeTablePS2.c (b210's numbering). Entries
pair by (name, format, n-th occurrence). Written:

  op233_of[our op]   2.3.3's number (0xFFFF: none), so code ported from
                     2.3.3 can switch on 2.3.3's numbers
  unit233[our op]    the unit byte 2.3.3 keeps at entry +0x26 (its
                     scheduler's machine model indexes five units by it)
"""

import collections
import os
import re
import sys

import capstone

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", "..", "..", ".."))
TREE = REPO  # the sources: src/psp/backend/
sys.path.insert(0, os.path.join(REPO, "tools", "mwccpsp"))
from pe import PE  # noqa: E402

EXE = os.environ.get("B233_EXE", os.path.join(REPO, "orig", "PS2_2_3_3", "mwccps2.exe"))
REAL, REALBITS, MACRO = 0x48A400, 0x48A510, 0x48A550


def table233(pe):
    def cstr(a):
        return pe.read(a, 64).split(b"\0")[0].decode("latin1") if a else ""

    md = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_32)
    md.detail = True
    stack, out = [], {}
    for ins in md.disasm(pe.read(0x48A600, 0x10000), 0x48A600):
        if ins.mnemonic == "push":
            o = ins.operands[0]
            stack.append(o.imm if o.type == capstone.x86.X86_OP_IMM else None)
        elif ins.mnemonic == "call":
            t = ins.operands[0].imm if ins.operands[0].type == capstone.x86.X86_OP_IMM else None
            if t == REAL:
                op, name, fmt, enc, flags, intr, unit, lat = stack[-8:][::-1]
                out[op] = (cstr(name), cstr(fmt), unit, lat)
            elif t == REALBITS:
                op, name, fmt, bits, flags, unit, lat = stack[-7:][::-1]
                out[op] = (cstr(name), cstr(fmt), unit, lat)
            elif t == MACRO:
                op, name, fmt, real, alt, lat = stack[-6:][::-1]
                out[op] = (cstr(name), cstr(fmt), 0, lat)
            if t in (REAL, REALBITS, MACRO):
                if None in (op, name, fmt):
                    sys.exit(f"0x{ins.address:X}: a register argument")
                stack = []
        elif ins.mnemonic == "ret":
            break
    return out


def ours():
    s = open(os.path.join(TREE, "src", "psp", "backend", "OpcodeTablePS2.c")).read()
    out = {}
    for kind, op, name, fmt in re.findall(r'func_00478(ED0|E30)\((\w+), "([^"]*)", "([^"]*)"', s):
        out.setdefault(int(op, 0), (name, fmt))  # the first definition (later ones are variants)
    return out


def main():
    pe = PE(EXE)
    t233, t = table233(pe), ours()
    key233 = collections.defaultdict(list)
    for op in sorted(t233):
        key233[t233[op][:2]].append(op)
    seen = collections.Counter()
    op233_of, unit = {}, {}
    for op in sorted(t):
        k = t[op]
        n = seen[k]
        seen[k] += 1
        if n < len(key233[k]):
            o = key233[k][n]
            op233_of[op] = o
            unit[op] = t233[o][2]
    n_ops = 0x4AF  # BE_NUM_OPDEFS (MWCCPS2)
    lines = [
        "// generated by tools/mwccps2/b233/re/gen_opmap233.py: do not edit",
        "// 2.3.3's opcode numbers and scheduler units for our opcode table",
        '#include "compiler/common.h"',
        "",
        "#if MWCC_CORE == MWCC_CORE_B233",
        "",
        f"const UInt16 op233_of[{n_ops:#x}] = {{",
    ]
    for i in range(0, n_ops, 8):
        lines.append("    " + " ".join(f"0x{op233_of.get(j, 0xFFFF):04X}," for j in range(i, min(i + 8, n_ops))))
    lines += ["};", "", f"const UInt8 unit233[{n_ops:#x}] = {{"]
    for i in range(0, n_ops, 16):
        lines.append("    " + " ".join(f"{unit.get(j, 0)}," for j in range(i, min(i + 16, n_ops))))
    lines += ["};", "", "#endif", ""]
    open(os.path.join(TREE, "src", "psp", "backend", "OpMap233.c"), "w").write("\n".join(lines))
    print(f"2.3.3: {len(t233)} entries; ours: {len(t)}; paired {len(op233_of)}")
    missing = sorted(set(t233) - set(op233_of.values()))
    print(f"2.3.3 entries with no pair: {len(missing)}: " + " ".join(f"{o:#x}:{t233[o][0]}" for o in missing[:40]))


if __name__ == "__main__":
    main()
